/** A car to follow, from its first keyframe until `to` (or the end of the scene). */
const car = (id: string, label: string, keyframes: HotspotKeyframe[], to?: number): Hotspot => ({
  type: "hotspot",
  id,
  from: keyframes[0].at,
  to,
  label,
  keyframes,
});

/**
 * The same path, moved up so a label rides above the car instead of covering
 * it. The pickup stays low enough for it to fit, even as it leaves at the top.
 */
const above = (keyframes: HotspotKeyframe[]): HotspotKeyframe[] =>
  keyframes.map(({ at, area }) => {
    const { x, y, width } = area!;
    return {
      at,
      area: { x: x - 0.05, y: Math.max(0, y - 0.07), width: width + 0.1, height: 0.06 },
    };
  });

/** The pickup again, on the replay, with the feedback riding along above it. */
const replay = (id: string, label: string): Story["scenes"][string] => ({
  src: video("traffic"),
  events: [
    { ...car(id, "White pickup", pickup), variant: "pulse" },
    { ...car(`${id}-label`, label, above(pickup)), variant: "label" },
  ],
});

